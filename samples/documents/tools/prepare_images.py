"""Turns the original public-domain photographs (MANIFEST.md lists their source URLs) into the images the documents use.

    python3 samples/documents/tools/prepare_images.py <folder of originals> <document>

The originals are not in the repository, only what this script makes from them. Every photograph is converted to sRGB from the
profile it carries, scaled to at most MAX_PIXELS, and saved as a baseline JPEG that embeds an sRGB profile generated by LittleCMS
(Pillow's ImageCms), so the profile is ours too. Some become CMYK JPEGs (a simple grey-component replacement, no profile:
DeviceCMYK) and some become PNG cut-outs with an alpha channel (an SMask in PDF). Needs Pillow.
"""

import io
import math
import os
import sys

from PIL import Image, ImageCms, ImageDraw, ImageFilter

MAX_PIXELS = 4_200_000
SRGB = ImageCms.ImageCmsProfile(ImageCms.createProfile('sRGB'))
SRGB_BYTES = SRGB.tobytes()

# document -> [(original, output, kind, options)]
PLANS = {
    'catalogue': [
        ('earth-apollo17.jpg', 'earth.jpg', 'rgb', {}),
        ('earthrise-apollo8.jpg', 'earthrise.jpg', 'rgb', {}),
        ('aldrin-apollo11.jpg', 'aldrin.jpg', 'rgb', {}),
        ('mccandless-eva.jpg', 'mccandless.jpg', 'rgb', {}),
        ('atlantis-sts27.jpg', 'atlantis.jpg', 'rgb', {}),
        ('columbia-launch.jpg', 'columbia-cmyk.jpg', 'cmyk', {}),
        ('aurora-iss.jpg', 'aurora-cmyk.jpg', 'cmyk', {}),
        ('rover-apollo15.jpg', 'rover-cmyk.jpg', 'cmyk', {}),
        ('earth-apollo17.jpg', 'earth-cutout.png', 'disc', {'size': 720, 'radius': 0.462, 'centre': (0.5, 0.505)}),
        ('mccandless-eva.jpg', 'mccandless-cutout.png', 'vignette', {'size': 760}),
    ],
}


def to_srgb(image):
    """Converts an image to sRGB from the ICC profile it embeds (or assumes sRGB)."""
    image = image.convert('RGB') if image.mode not in ('RGB',) else image
    icc = image.info.get('icc_profile')
    if icc:
        source = ImageCms.ImageCmsProfile(io.BytesIO(icc))
        image = ImageCms.profileToProfile(image, source, SRGB, outputMode='RGB')
    return image


def fit(image, max_pixels, upscale=0):
    w, h = image.size
    if w * h > max_pixels:
        k = math.sqrt(max_pixels / (w * h))
    elif upscale and w * h < upscale:
        k = math.sqrt(upscale / (w * h))
    else:
        return image
    return image.resize((round(w * k), round(h * k)), Image.Resampling.LANCZOS)


def cmyk(image):
    """RGB to CMYK with full grey-component replacement (K = 1 - max(R, G, B)), then 85% of the grey back into CMY."""
    px = image.load()
    out = Image.new('CMYK', image.size)
    po = out.load()
    w, h = image.size
    for y in range(h):
        for x in range(w):
            rr, gg, bb = px[x, y]
            k = 255 - max(rr, gg, bb)
            if k == 255:
                po[x, y] = (0, 0, 0, 255)
                continue
            d = 255 - k
            c = (d - rr) * 255 // d
            m = (d - gg) * 255 // d
            yy = (d - bb) * 255 // d
            k2 = k * 85 // 100
            # Put 15% of the black back into the chromatic inks so dark areas stay rich.
            extra = k - k2
            po[x, y] = (min(255, c + extra), min(255, m + extra), min(255, yy + extra), k2)
    return out


def main():
    originals, document = sys.argv[1], sys.argv[2]
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', document, 'images')
    os.makedirs(here, exist_ok=True)
    for source, output, kind, options in PLANS[document]:
        image = to_srgb(Image.open(os.path.join(originals, source)))
        path = os.path.join(here, output)
        if kind == 'rgb':
            fit(image, MAX_PIXELS, options.get('upscale', 0)).save(path, quality=82, icc_profile=SRGB_BYTES, optimize=True)
        elif kind == 'cmyk':
            cmyk(fit(image, MAX_PIXELS // 2, options.get('upscale', 0))).save(path, quality=78, optimize=True)
        elif kind == 'disc':
            w, h = image.size
            cx, cy = options['centre']
            r = options['radius'] * min(w, h)
            box = (round(cx * w - r), round(cy * h - r), round(cx * w + r), round(cy * h + r))
            size = options['size']
            disc = image.crop(box).resize((size, size), Image.Resampling.LANCZOS).convert('RGBA')
            mask = Image.new('L', (size * 4, size * 4), 0)
            ImageDraw.Draw(mask).ellipse((8, 8, size * 4 - 8, size * 4 - 8), fill=255)
            mask = mask.resize((size, size), Image.Resampling.LANCZOS).filter(ImageFilter.GaussianBlur(1.2))
            disc.putalpha(mask)
            disc.save(path, optimize=True)
        elif kind == 'vignette':
            size = options['size']
            square = image.resize((size, size), Image.Resampling.LANCZOS).convert('RGBA')
            mask = Image.radial_gradient('L').resize((size, size), Image.Resampling.BICUBIC)
            mask = mask.point(lambda v: 255 if v < 110 else max(0, 255 - (v - 110) * 255 // 60))
            square.putalpha(mask)
            square.save(path, optimize=True)
        print(f'{output}: {os.path.getsize(path):,} bytes')


if __name__ == '__main__':
    main()
