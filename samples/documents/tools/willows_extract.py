"""Builds novel/willows.html and novel/willows.json from The Wind in the Willows (Kenneth Grahame, 1908; public domain in the US).

    python3 samples/documents/tools/willows_extract.py <pg289.txt>

The input is Project Gutenberg eBook #289 as plain text (https://www.gutenberg.org/ebooks/289). Only the novel's text is used: the
Project Gutenberg header, footer and licence and the illustration markers are dropped, and the output does not use the Project
Gutenberg name. willows.html is the source of the two WeasyPrint editions (each adds its own stylesheet); willows.json holds the same
chapters for the large-print edition that Broadside lays out.
"""

import html
import json
import os
import re
import sys

TITLES = ['THE RIVER BANK', 'THE OPEN ROAD', 'THE WILD WOOD', 'MR. BADGER', 'DULCE DOMUM', 'MR. TOAD', 'THE PIPER AT THE GATES OF DAWN',
          'TOAD’S ADVENTURES', 'WAYFARERS ALL', 'THE FURTHER ADVENTURES OF TOAD', '“LIKE SUMMER TEMPESTS CAME HIS TEARS”',
          'THE RETURN OF ULYSSES']
ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII']


def title_case(title):
    small = {'of', 'the', 'at', 'in', 'his'}
    words = title.lower().split()
    return ' '.join(w if (i and w in small) else w[:1].upper() + w[1:] if not w.startswith('“') else '“' + w[1:2].upper() + w[2:]
                    for i, w in enumerate(words))


def preceded_by_numeral(lines, i):
    j = i - 1
    while j >= 0 and not lines[j].strip():
        j -= 1
    return j >= 0 and re.fullmatch(r'[IVX]+\.', lines[j].strip()) is not None


def main():
    text = open(sys.argv[1], encoding='utf-8').read().replace('\r\n', '\n')
    body = text[text.index('*** START OF THE PROJECT GUTENBERG'):text.index('*** END OF THE PROJECT GUTENBERG')]
    lines = body.split('\n')
    starts = []
    search = 0
    for title in TITLES:
        # The chapter title stands alone on its line, after the table of contents.
        index = next(i for i in range(search, len(lines)) if lines[i].strip() == title and preceded_by_numeral(lines, i))
        starts.append(index)
        search = index + 1
    chapters = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        chunk = '\n'.join(lines[start + 1:end])
        chunk = chunk.replace('[Illustration]', '')
        if n + 1 < len(starts):
            chunk = re.sub(r'\n\s*[IVX]+\.\s*$', '', chunk.rstrip())  # the next chapter's numeral
        paragraphs = [re.sub(r'\s+', ' ', p).strip() for p in re.split(r'\n\s*\n', chunk)]
        paragraphs = [p for p in paragraphs if p and p not in ('THE END',)]
        chapters.append({'number': ROMAN[n], 'title': title_case(TITLES[n]), 'paragraphs': paragraphs})

    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'novel')
    os.makedirs(here, exist_ok=True)
    with open(os.path.join(here, 'willows.json'), 'w', encoding='utf-8') as f:
        json.dump({'title': 'The Wind in the Willows', 'author': 'Kenneth Grahame', 'year': 1908, 'chapters': chapters}, f,
                  ensure_ascii=False, indent=0)

    out = ['<!DOCTYPE html>', '<html lang="en-GB">', '<head>', '<meta charset="utf-8">', '<title>The Wind in the Willows</title>',
           '<meta name="author" content="Kenneth Grahame">',
           '<meta name="description" content="The Wind in the Willows (1908), public domain in the US, typeset for the Broadside project.">',
           '<meta name="generator" content="WeasyPrint">',
           '<meta name="dcterms.created" content="2026-10-25T00:00:00Z">', '<meta name="dcterms.modified" content="2026-10-25T00:00:00Z">',
           '<!-- Generated by tools/willows_extract.py; each edition adds its stylesheet with weasyprint -s. -->', '</head>', '<body>',
           '<section class="half-title"><h1 class="book">The Wind in the Willows</h1></section>',
           '<section class="title-page"><h1>The Wind in the Willows</h1><p class="by">Kenneth Grahame</p>'
           '<p class="imprint">First published in 1908. This text is in the public domain in the United States.<br>'
           'Typeset for the Broadside project as a sample document.</p></section>',
           '<nav class="contents"><h2>Contents</h2><ol>']
    for n, ch in enumerate(chapters):
        out.append(f'<li><a href="#ch{n + 1}"><span class="num">{ch["number"]}</span> {html.escape(ch["title"])}</a></li>')
    out.append('</ol></nav>')
    for n, ch in enumerate(chapters):
        out.append(f'<section class="chapter" id="ch{n + 1}">')
        out.append(f'<h2><span class="num">Chapter {ch["number"]}</span> <span class="title">{html.escape(ch["title"])}</span></h2>')
        for i, p in enumerate(ch['paragraphs']):
            cls = ' class="first"' if i == 0 else ''
            # The transcription marks italics with underscores (kept as they are in willows.json).
            out.append(f'<p{cls}>{re.sub(r"_([^_]+)_", r"<i>\1</i>", html.escape(p, quote=False))}</p>')
        out.append('</section>')
    out.append('<p class="end">The End</p>')
    out += ['</body>', '</html>', '']
    with open(os.path.join(here, 'willows.html'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    words = sum(len(p.split()) for ch in chapters for p in ch['paragraphs'])
    print(f'{len(chapters)} chapters, {words:,} words')


if __name__ == '__main__':
    main()
