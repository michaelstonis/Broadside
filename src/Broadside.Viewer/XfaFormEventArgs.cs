using Broadside.Forms;

namespace Broadside.Viewer;

/// <summary>
/// The notice a viewer shows for a document whose interactive form carries an XFA form: Broadside neither renders nor runs XFA, so
/// the viewer shows the pages and the AcroForm fields, and filling writes the AcroForm values only.
/// </summary>
/// <remarks>
/// ISO 32000-2 §12.7.3 (Table 224) and Annex K (XFA forms; the <c>XFA</c> entry of the interactive form dictionary is deprecated
/// in PDF 2.0) and §7.7.2, Table 29 (<c>NeedsRendering</c>: a dynamic form whose pages the XFA describes). Spec #33 viewer
/// capability 12; XFA stays parse-and-preserve.
/// </remarks>
public sealed class XfaFormEventArgs : EventArgs
{
    private XfaFormEventArgs(bool isDynamic, int packetCount)
    {
        IsDynamic = isDynamic;
        PacketCount = packetCount;
    }

    /// <summary>
    /// Gets a value indicating whether the XFA form is dynamic (the catalog's <c>NeedsRendering</c> is true): its pages exist only in
    /// the XFA, so the PDF pages shown may be a placeholder.
    /// </summary>
    public bool IsDynamic { get; }

    /// <summary>Gets how many XFA packets the form has (one when <c>XFA</c> is a single stream).</summary>
    public int PacketCount { get; }

    /// <summary>Gets a sentence or two explaining, for the user, what the viewer does with the form.</summary>
    public string Explanation => IsDynamic
        ? "This document is a dynamic XFA form. Its pages are generated by XFA, which this viewer does not run, so what is shown may be a placeholder page; the form cannot be filled here."
        : "This document contains an XFA form, which this viewer does not run. The pages and their AcroForm fields are shown and can be filled; values are saved to the AcroForm fields only, not to the XFA data.";

    /// <summary>Returns the notice for a document, or <see langword="null"/> when its form has no XFA.</summary>
    internal static XfaFormEventArgs? For(PdfDocument document) =>
        document.AcroForm?.Xfa is PdfXfaForm xfa ? new XfaFormEventArgs(xfa.IsDynamic, xfa.Packets.Count) : null;
}
