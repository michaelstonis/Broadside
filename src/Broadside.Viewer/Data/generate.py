#!/usr/bin/env python3
"""Generates the compatibility decomposition table viewer search folds text with.

Run with ``python3 -I src/Broadside.Viewer/Data/generate.py`` (stdlib only). The table comes from Python's ``unicodedata``
module, whose Unicode version is checked below, so re-running it with a Python of that version reproduces the output byte for
byte. Decomposition mappings are stable across Unicode versions (only new characters add entries), so a newer version only
adds rows; bump ``VERSION`` deliberately and regenerate.

Why a table: ``string.Normalize`` needs the host's globalization data, and applications built with ``InvariantGlobalization``
(the browser among them) leave non-ASCII text unchanged, so search could not fold "é" to "e" or "ﬁ" to "fi" there.

Output: ``src/Broadside.Viewer/SearchFoldingData.g.cs``: every BMP character other than a Hangul syllable whose full
compatibility decomposition (NFKD) differs from itself, sorted for binary search, with its decomposition.
"""

from __future__ import annotations

import os
import sys
import unicodedata

VERSION = "17.0.0"
OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "SearchFoldingData.g.cs")


def escape(text: str) -> str:
    out = []
    for unit in text.encode("utf-16-le").hex(" ", 2).split(" "):
        value = int(unit[2:4] + unit[0:2], 16)
        out.append(f"\\u{value:04X}")
    return "".join(out)


def main() -> int:
    if unicodedata.unidata_version != VERSION:
        print(f"unicodedata is {unicodedata.unidata_version}; this table is generated from {VERSION}", file=sys.stderr)
        return 1

    keys: list[str] = []
    values: list[str] = []
    for code in range(0x80, 0x10000):
        if 0xAC00 <= code <= 0xD7A3 or 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        decomposed = unicodedata.normalize("NFKD", char)
        if decomposed != char:
            keys.append(char)
            values.append(decomposed)

    offsets = [0]
    for value in values:
        offsets.append(offsets[-1] + len(value.encode("utf-16-le")) // 2)

    lines = [
        "// <auto-generated>",
        f"// Generated by src/Broadside.Viewer/Data/generate.py from Python's unicodedata (Unicode {VERSION}). Do not edit; regenerate.",
        "// Unicode data: Copyright (c) 1991-2025 Unicode, Inc. Unicode License v3, https://www.unicode.org/terms_of_use.html",
        "// </auto-generated>",
        "",
        "namespace Broadside.Viewer;",
        "",
        f"/// <summary>The full compatibility decompositions (NFKD) of the BMP characters that have one, Hangul syllables aside (Unicode {VERSION}).</summary>",
        "internal static class SearchFoldingData",
        "{",
        f"    /// <summary>The {len(keys)} characters, ascending.</summary>",
        "    public static ReadOnlySpan<char> Keys =>",
    ]
    for start in range(0, len(keys), 24):
        chunk = "".join(keys[start:start + 24])
        end = ";" if start + 24 >= len(keys) else " +"
        lines.append(f'        "{escape(chunk)}"{end}')
    lines.append("")
    lines.append("    /// <summary>Where each key's decomposition starts in <see cref=\"Values\"/>; one more entry than keys.</summary>")
    lines.append("    public static ReadOnlySpan<ushort> Offsets =>")
    lines.append("    [")
    for start in range(0, len(offsets), 16):
        lines.append("        " + ", ".join(str(o) for o in offsets[start:start + 16]) + ",")
    lines.append("    ];")
    lines.append("")
    lines.append("    /// <summary>The decompositions, one after the other.</summary>")
    lines.append("    public static ReadOnlySpan<char> Values =>")
    joined = "".join(values)
    units = len(joined.encode("utf-16-le")) // 2
    pieces = []
    current = ""
    for char in joined:
        current += char
        if len(current) >= 24:
            pieces.append(current)
            current = ""
    if current:
        pieces.append(current)
    for index, piece in enumerate(pieces):
        end = ";" if index == len(pieces) - 1 else " +"
        lines.append(f'        "{escape(piece)}"{end}')
    lines.append("}")
    lines.append("")
    assert offsets[-1] == units

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
