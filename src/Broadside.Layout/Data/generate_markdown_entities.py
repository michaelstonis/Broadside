#!/usr/bin/env python3
"""Generates the HTML named character references the Markdown parser of Broadside.Layout decodes.

Run with ``python3 -I src/Broadside.Layout/Data/generate_markdown_entities.py <entities.json>`` (stdlib only), where
``<entities.json>`` is https://html.spec.whatwg.org/entities.json downloaded unmodified (license: the WHATWG HTML
standard, CC BY 4.0). CommonMark 0.31 recognizes an entity reference only with its closing semicolon, so the names
without one are dropped. The output is deterministic: re-running it on the same input reproduces it byte for byte.

Output: ``src/Broadside.Layout/MarkdownEntities.g.cs``, one string of ``name=hex[,hex];`` entries sorted by
name, parsed into a dictionary on first use.
"""

from __future__ import annotations

import json
import os
import sys


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: generate_markdown_entities.py <entities.json>")
    with open(sys.argv[1], encoding="utf-8") as stream:
        entities = json.load(stream)
    entries = []
    for name in sorted(entities):
        if not (name.startswith("&") and name.endswith(";")):
            continue
        hex_points = ",".join(f"{point:X}" for point in entities[name]["codepoints"])
        entries.append(f"{name[1:-1]}={hex_points};")
    lines = []
    line = ""
    for entry in entries:
        if len(line) + len(entry) > 100:
            lines.append(line)
            line = ""
        line += entry
    if line:
        lines.append(line)
    body = "\n".join(f'        "{chunk}" +' for chunk in lines)
    body = body[: -len(" +")]
    source = f"""// <auto-generated>
// Generated by src/Broadside.Layout/Data/generate_markdown_entities.py from the WHATWG HTML entities.json; do not edit.
// </auto-generated>

namespace Broadside.Layout.Flow;

internal static partial class MarkdownEntities
{{
    /// <summary>The {len(entries)} named character references of HTML that end in a semicolon, as <c>name=hex[,hex];</c> sorted by name.</summary>
    private const string Table =
{body};
}}
"""
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "MarkdownEntities.g.cs")
    with open(out, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(source)


if __name__ == "__main__":
    main()
