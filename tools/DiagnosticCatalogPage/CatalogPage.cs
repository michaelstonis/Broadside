using System.Globalization;
using System.Text;
using Broadside.Diagnostics;

namespace Broadside.Tools.DiagnosticCatalogPage;

/// <summary>
/// The diagnostic catalog as the documentation site's page shows it, generated from <see cref="DiagnosticCatalog.All"/>. The page
/// holds it between <see cref="BeginMarker"/> and <see cref="EndMarker"/>; the rest of the page (the stability policy) is written by hand.
/// Linked into Broadside.Tests too, so a stale page fails the test suite as well as the documentation build.
/// </summary>
public static class CatalogPage
{
    /// <summary>The line that opens the generated block.</summary>
    public const string BeginMarker = "<!-- diagnostic-catalog:begin (generated by tools/DiagnosticCatalogPage --write; do not edit) -->";

    /// <summary>The line that closes the generated block.</summary>
    public const string EndMarker = "<!-- diagnostic-catalog:end -->";

    /// <summary>Renders the block: a count, then one table per area in catalog order, one row per code.</summary>
    public static string Render()
    {
        var text = new StringBuilder();
        text.Append(CultureInfo.InvariantCulture, $"The catalog has {DiagnosticCatalog.All.Count} codes in {DiagnosticCatalog.All.Select(code => code.Area).Distinct().Count()} areas.\n");
        foreach (IGrouping<DiagnosticArea, DiagnosticCode> area in DiagnosticCatalog.All.GroupBy(code => code.Area))
        {
            text.Append('\n').Append("### ").Append(Words(area.Key.ToString())).Append("\n\n");
            text.Append(CultureInfo.InvariantCulture, $"Codes of `{area.Key}Diagnostics`, reported under `DiagnosticArea.{area.Key}`.\n\n");
            text.Append("| Code | Default severity | Clause | Meaning and typical repair |\n");
            text.Append("|---|---|---|---|\n");
            foreach (DiagnosticCode code in area)
            {
                text.Append("| `").Append(code.Name).Append("` | ").Append(code.DefaultSeverity.ToString())
                    .Append(" | ").Append(Cell(code.Clause)).Append(" | ").Append(Cell(code.Description)).Append(" |\n");
            }
        }

        return text.ToString();
    }

    /// <summary>Whether the page's generated block equals <see cref="Render"/>; a page without the markers is stale.</summary>
    /// <param name="page">The page's text.</param>
    public static bool IsCurrent(string page)
    {
        ArgumentNullException.ThrowIfNull(page);
        string text = Normalize(page);
        return TryFindBlock(text, out int start, out int end) && string.Equals(text[start..end], Render(), StringComparison.Ordinal);
    }

    /// <summary>The page with its generated block replaced by <see cref="Render"/>.</summary>
    /// <param name="page">The page's text.</param>
    /// <exception cref="InvalidDataException">The page has no block between the markers.</exception>
    public static string Update(string page)
    {
        ArgumentNullException.ThrowIfNull(page);
        string text = Normalize(page);
        if (!TryFindBlock(text, out int start, out int end))
        {
            throw new InvalidDataException($"The page has no '{BeginMarker}' line followed by an '{EndMarker}' line.");
        }

        return string.Concat(text.AsSpan(0, start), Render(), text.AsSpan(end));
    }

    private static string Cell(string? value) => string.IsNullOrEmpty(value) ? string.Empty : value.Replace("|", "\\|", StringComparison.Ordinal);

    // FileStructure -> File structure, CMap -> CMap, Jbig2 -> Jbig2.
    private static string Words(string pascal)
    {
        var text = new StringBuilder();
        for (int i = 0; i < pascal.Length; i++)
        {
            char c = pascal[i];
            bool boundary = i > 0 && char.IsAsciiLetterUpper(c) && char.IsAsciiLetterLower(pascal[i - 1]);
            if (boundary)
            {
                text.Append(' ').Append(char.ToLowerInvariant(c));
            }
            else
            {
                text.Append(c);
            }
        }

        return text.ToString();
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    private static bool TryFindBlock(string text, out int start, out int end)
    {
        int begin = text.IndexOf(BeginMarker + "\n", StringComparison.Ordinal);
        start = begin < 0 ? -1 : begin + BeginMarker.Length + 1;
        end = start < 0 ? -1 : text.IndexOf(EndMarker, start, StringComparison.Ordinal);
        return start >= 0 && end >= 0;
    }
}
