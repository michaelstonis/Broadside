using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Broadside.Tools.ConformanceCheck;

/// <summary>
/// The per-specification counts the documentation site's conformance page shows, generated from the maps. The page holds them
/// between <see cref="BeginMarker"/> and <see cref="EndMarker"/>; <c>--site-page</c> fails when that block differs from what
/// the maps give, and <c>--write-site-page</c> regenerates it.
/// </summary>
public static partial class SiteCounts
{
    /// <summary>The line that opens the generated block.</summary>
    public const string BeginMarker = "<!-- conformance-counts:begin (generated by tools/ConformanceCheck --write-site-page; do not edit) -->";

    /// <summary>The line that closes the generated block.</summary>
    public const string EndMarker = "<!-- conformance-counts:end -->";

    /// <summary>
    /// Renders the block's content: one row per map, named by the specification <c>docs/conformance/README.md</c> gives it
    /// (the file name when the README does not list it), with its counts per status, then a total row.
    /// </summary>
    /// <param name="report">The checked maps.</param>
    /// <param name="repositoryRoot">The repository root, to read the README's specification names from.</param>
    public static string Render(ConformanceReport report, string repositoryRoot)
    {
        ArgumentNullException.ThrowIfNull(report);
        Dictionary<string, string> names = ReadSpecificationNames(repositoryRoot);

        var text = new StringBuilder();
        text.Append("| Specification | Map | done | partial | not started | n/a | Rows |\n");
        text.Append("|---|---|---:|---:|---:|---:|---:|\n");
        foreach (ConformanceFile file in report.Files)
        {
            string fileName = Path.GetFileName(file.File);
            string name = names.TryGetValue(fileName, out string? specification) ? specification : fileName;
            AppendRow(text, name.Replace("|", "\\|", StringComparison.Ordinal), $"`{fileName}`", file.Count, file.Rows.Count);
        }

        AppendRow(text, "**Total**", string.Empty, status => report.Files.Sum(file => file.Count(status)), report.RowCount);
        return text.ToString();
    }

    /// <summary>Whether the page's generated block equals <paramref name="expected"/>; a page without the markers is stale.</summary>
    /// <param name="page">The page's text.</param>
    /// <param name="expected">The block's content from <see cref="Render"/>.</param>
    public static bool IsCurrent(string page, string expected)
    {
        ArgumentNullException.ThrowIfNull(page);
        return TryFindBlock(Normalize(page), out int start, out int end) && string.Equals(Normalize(page)[start..end], expected, StringComparison.Ordinal);
    }

    /// <summary>The page with its generated block replaced by <paramref name="expected"/>.</summary>
    /// <param name="page">The page's text.</param>
    /// <param name="expected">The block's content from <see cref="Render"/>.</param>
    /// <exception cref="InvalidDataException">The page has no block between the markers.</exception>
    public static string Update(string page, string expected)
    {
        ArgumentNullException.ThrowIfNull(page);
        string text = Normalize(page);
        if (!TryFindBlock(text, out int start, out int end))
        {
            throw new InvalidDataException($"The page has no '{BeginMarker}' line followed by an '{EndMarker}' line.");
        }

        return string.Concat(text.AsSpan(0, start), expected, text.AsSpan(end));
    }

    private static void AppendRow(StringBuilder text, string name, string map, Func<string, int> count, int rows)
    {
        text.Append("| ").Append(name).Append(" | ").Append(map).Append(" |");
        foreach (string status in (string[])[ConformanceStatus.Done, ConformanceStatus.Partial, ConformanceStatus.NotStarted, ConformanceStatus.NotApplicable])
        {
            text.Append(' ').Append(count(status).ToString(CultureInfo.InvariantCulture)).Append(" |");
        }

        text.Append(' ').Append(rows.ToString(CultureInfo.InvariantCulture)).Append(" |\n");
    }

    /// <summary>The block's content runs from the line after the begin marker to the start of the end marker's line.</summary>
    private static bool TryFindBlock(string text, out int start, out int end)
    {
        start = end = 0;
        int begin = text.IndexOf(BeginMarker + "\n", StringComparison.Ordinal);
        if (begin < 0)
        {
            return false;
        }

        start = begin + BeginMarker.Length + 1;
        end = text.IndexOf(EndMarker, start, StringComparison.Ordinal);
        return end >= 0 && (end == 0 || text[end - 1] == '\n');
    }

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    /// <summary>Reads the README's file table: <c>| [iso-32000-2.md](./iso-32000-2.md) | ISO 32000-2:2020 PDF 2.0 |</c>.</summary>
    private static Dictionary<string, string> ReadSpecificationNames(string repositoryRoot)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        string readme = Path.Combine(repositoryRoot, "docs", "conformance", "README.md");
        if (!File.Exists(readme))
        {
            return names;
        }

        foreach (string line in File.ReadLines(readme))
        {
            Match match = ReadmeRow().Match(line);
            if (match.Success)
            {
                names[match.Groups["file"].Value] = OpenDecision().Replace(match.Groups["name"].Value.Trim(), string.Empty);
            }
        }

        return names;
    }

    [GeneratedRegex(@"^\|\s*\[(?<file>[^\]]+\.md)\]\([^)]*\)\s*\|(?<name>[^|]+)\|\s*$")]
    private static partial Regex ReadmeRow();

    /// <summary>The README's planning reference, which means nothing on the site: <c> (open decision 12)</c>.</summary>
    [GeneratedRegex(@"\s*\(open decision \d+\)$")]
    private static partial Regex OpenDecision();
}
