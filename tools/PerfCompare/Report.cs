using System.Globalization;
using System.Text;

namespace Broadside.Tools.PerfCompare;

/// <summary>Writes the comparison report (Markdown) from one or more result sets, one section per machine.</summary>
internal static class Report
{
    private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

    /// <summary>The operations in the order the report lists them, with what each one times.</summary>
    private static readonly (string Op, string Name, string Meaning)[] Operations =
    [
        ("open", "Open", "Open the file from memory and read the page's size."),
        ("text", "Extract text", "On an open document, extract the page's text."),
        ("render", "Render", "On an open document, render the page again (fonts and images already loaded, the page's content read again)."),
        ("open-render", "First render", "Open the file and render the page: what a viewer pays to show it the first time."),
        ("document", "Whole document", "Open the file and render every page."),
    ];

    public static string Write(IReadOnlyList<ResultSet> sets)
    {
        var text = new StringBuilder();
        text.AppendLine("# Performance comparison with PDFium and pdf.js");
        text.AppendLine();
        text.AppendLine("<!-- Generated by bench/perf-report.sh (tools/PerfCompare). Do not edit by hand: run the script again. -->");
        text.AppendLine();
        text.AppendLine("How fast Broadside opens, renders and extracts text from real-world PDFs, next to PDFium (the engine in Chrome) and pdf.js");
        text.AppendLine("(the engine in Firefox), and how much memory each needs. Ratios are Broadside's time divided by the other engine's: below 1");
        text.AppendLine("means Broadside is faster.");
        text.AppendLine();
        WriteMethod(text, sets);
        foreach (ResultSet set in sets)
        {
            WriteSet(text, set);
        }

        return text.ToString();
    }

    private static void WriteMethod(StringBuilder text, IReadOnlyList<ResultSet> sets)
    {
        text.AppendLine("## How it is measured");
        text.AppendLine();
        text.AppendLine("- **Pages.** The 21 pinned pages of the rendering gate (`tests/Broadside.Rendering.Tests/CorpusGate/pinned-pages.txt`), from 20");
        text.AppendLine("  files of the pdf.js, Ghent Workgroup and PDF Association test suites. They were picked to cover features (blend modes, spot");
        text.AppendLine("  colors, every image format, shadings, patterns, soft masks, embedded fonts), not for speed.");
        text.AppendLine("- **Engines.** Broadside with its software rasterizer on .NET; PDFium through pypdfium2; pdf.js in Node with its in-process");
        text.AppendLine("  worker and `@napi-rs/canvas`. Each runs in its own process with the same protocol (`tools/PerfCompare`,");
        text.AppendLine("  `tools/RenderDiff/reference/pdfium/bench.py`, `tools/RenderDiff/reference/pdfjs/bench.mjs`).");
        text.AppendLine("- **Protocol.** Each case warms up untimed for 0.5 s or 20 runs, whichever comes first, then is timed for up to the");
        text.AppendLine("  configured number of runs (at least 3, fewer once a case has used 10 s). Times are medians. Everything runs on one thread.");
        text.AppendLine("- **Fonts.** Broadside uses its bundled Standard 14 fonts and CMaps and no system fonts; the others use their own bundled fonts.");
        text.AppendLine("- **Cold and warm.** *First render* and *whole document* open a fresh copy of the file each run, so nothing from an earlier");
        text.AppendLine("  run is reused. *Render* and *extract text* reuse an open document, as a viewer does when it redraws a page. The process");
        text.AppendLine("  itself is always warm (code compiled, files in the OS cache).");
        text.AppendLine("- **Memory.** A fresh process per engine and file opens the file, renders every page at 150 DPI and extracts its text,");
        text.AppendLine("  then reports its peak resident set size. The table shows the peak minus the same process with the engine loaded and");
        text.AppendLine("  nothing opened, so each runtime's own size (Python, Node, .NET) is left out.");
        text.AppendLine("- **Browser.** Broadside's Blazor WebAssembly demo (AOT build, software rasterizer, main thread) and pdf.js (its Web");
        text.AppendLine("  Worker and a canvas) time the same pages in the same headless Chromium, on a cross-origin isolated page so the clock is");
        text.AppendLine("  precise. pdf.js renders with its print intent: its display intent waits for an animation frame, which adds about 8 ms to");
        text.AppendLine("  every render whatever the page holds. The two intents differ only for content hidden when printing. After each render pdf.js");
        text.AppendLine("  reads one pixel back from its canvas, which waits for the GPU to finish drawing, so both times include the pixels.");
        text.AppendLine();
        text.AppendLine("| Operation | What is timed |");
        text.AppendLine("|---|---|");
        foreach ((_, string name, string meaning) in Operations)
        {
            text.AppendLine(Invariant, $"| {name} | {meaning} |");
        }

        text.AppendLine();
        text.AppendLine("Shared machines and CI runners are noisy: expect 10 to 30% between runs, more on pages that take under a millisecond.");
        text.AppendLine(Invariant, $"Results below: {string.Join(", ", sets.Select(static s => s.Label))}.");
        text.AppendLine();
    }

    private static void WriteSet(StringBuilder text, ResultSet set)
    {
        text.AppendLine(Invariant, $"## {set.Label}");
        text.AppendLine();
        if (set.Environment.Count > 0)
        {
            text.AppendLine("| | |");
            text.AppendLine("|---|---|");
            foreach ((string key, string value) in set.Environment.Where(static pair => pair.Key is not ("label" or "slug")))
            {
                text.AppendLine(Invariant, $"| {key} | {value.Replace("|", "\\|", StringComparison.Ordinal)} |");
            }

            text.AppendLine();
        }

        IReadOnlyList<Timing> broadside = set.Engines["broadside"];
        text.AppendLine("### Summary");
        text.AppendLine();
        text.AppendLine("Geometric mean of the per-page ratios, and the slowest page relative to the other engine.");
        text.AppendLine();
        text.AppendLine("| Operation | DPI | Pages | vs PDFium | slowest page | vs pdf.js | slowest page |");
        text.AppendLine("|---|---:|---:|---:|---:|---:|---:|");
        foreach ((string op, string name, _) in Operations)
        {
            foreach (int? dpi in broadside.Where(t => t.Op == op).Select(static t => t.Dpi).Distinct().Order())
            {
                Ratios pdfium = Ratios.Of(broadside, set.Engines["pdfium"], op, dpi);
                Ratios pdfjs = Ratios.Of(broadside, set.Engines["pdfjs"], op, dpi);
                text.AppendLine(Invariant, $"| {name} | {dpi?.ToString(Invariant) ?? ""} | {Math.Max(pdfium.Count, pdfjs.Count)} | {pdfium.MeanText} | {pdfium.WorstText} | {pdfjs.MeanText} | {pdfjs.WorstText} |");
            }
        }

        text.AppendLine();
        WriteTargets(text, set);
        WriteBrowser(text, set);
        WriteMemory(text, set);
        WritePages(text, set);
    }

    private static void WriteTargets(StringBuilder text, ResultSet set)
    {
        IReadOnlyList<Timing> broadside = set.Engines["broadside"];
        IReadOnlyList<Timing> pdfium = set.Engines["pdfium"];
        IReadOnlyList<Timing> pdfjs = set.Engines["pdfjs"];
        var rows = new List<(string Target, string Measured, bool Met)>();

        foreach (int dpi in new[] { 72, 150 })
        {
            Ratios render = Ratios.Of(broadside, pdfium, "render", dpi);
            rows.Add(($"Render at {dpi} DPI: at most 1.0x PDFium on average, no page over 3x", $"{render.MeanText}, slowest {render.WorstText}", render.Count > 0 && render.Mean <= 1.0 && render.Worst <= 3.0));
        }

        foreach (int dpi in new[] { 72, 150 })
        {
            Ratios first = Ratios.Of(broadside, pdfium, "open-render", dpi);
            rows.Add(($"First render at {dpi} DPI: at most 1.25x PDFium on average, no page over 4x", $"{first.MeanText}, slowest {first.WorstText}", first.Count > 0 && first.Mean <= 1.25 && first.Worst <= 4.0));
        }

        var slower = new List<string>();
        foreach ((string op, _, _) in Operations)
        {
            foreach (int? dpi in broadside.Where(t => t.Op == op).Select(static t => t.Dpi).Distinct())
            {
                Ratios ratios = Ratios.Of(broadside, pdfjs, op, dpi);
                slower.AddRange(ratios.Pairs.Where(static p => p.Ratio > 1.0).Select(p => string.Create(Invariant, $"{Short(p.Page)} {op}{(dpi is null ? "" : $" {dpi}")} ({p.Ratio:0.0#}x)")));
            }
        }

        rows.Add(("Never slower than pdf.js (Node) on any page and operation", slower.Count == 0 ? "no slower case" : $"{slower.Count} slower: {string.Join("; ", slower.Take(6))}{(slower.Count > 6 ? "; ..." : "")}", slower.Count == 0));

        Ratios open = Ratios.Of(broadside, pdfium, "open", null);
        Ratios text2 = Ratios.Of(broadside, pdfium, "text", null);
        rows.Add(("Open: under 0.25x PDFium on average", open.MeanText, open.Count > 0 && open.Mean < 0.25));
        rows.Add(("Extract text: under 0.5x PDFium on average", text2.MeanText, text2.Count > 0 && text2.Mean < 0.5));

        List<Timing> allocations = [.. broadside.Where(static t => t.Op == "render" && t.Dpi == 72 && t.AllocBytes is not null)];
        List<Timing> over = [.. allocations.Where(static t => t.AllocBytes > 1024 * 1024)];
        rows.Add(("Render at 72 DPI allocates at most 1 MB per page", over.Count == 0 ? $"largest {Bytes(allocations.Count == 0 ? 0 : allocations.Max(static t => t.AllocBytes!.Value))}" : string.Join("; ", over.Select(static t => $"{Short(t.File)} {Bytes(t.AllocBytes!.Value)}")), allocations.Count > 0 && over.Count == 0));

        text.AppendLine("### Targets");
        text.AppendLine();
        text.AppendLine("The targets proposed with the Phase 3 baseline (issue #140). A missed target blocks 1.0 unless the owner accepts it in writing.");
        text.AppendLine();
        text.AppendLine("| Target | Measured | Status |");
        text.AppendLine("|---|---|---|");
        foreach ((string target, string measured, bool met) in rows)
        {
            text.AppendLine(Invariant, $"| {target} | {measured} | {(met ? "met" : "**missed**")} |");
        }

        text.AppendLine();
    }

    private static void WriteBrowser(StringBuilder text, ResultSet set)
    {
        IReadOnlyList<Timing> broadside = set.Browser["broadside"];
        IReadOnlyList<Timing> pdfjs = set.Browser["pdfjs"];
        if (broadside.Count == 0 || pdfjs.Count == 0)
        {
            return;
        }

        text.AppendLine("### In the browser");
        text.AppendLine();
        text.AppendLine("Broadside's WebAssembly build against pdf.js in the same Chromium. Ratios are Broadside's time over pdf.js's.");
        text.AppendLine();
        text.AppendLine("| Operation | DPI | Pages | vs pdf.js | slowest page | fastest page |");
        text.AppendLine("|---|---:|---:|---:|---:|---:|");
        foreach ((string op, string name, _) in Operations)
        {
            foreach (int? dpi in broadside.Where(t => t.Op == op).Select(static t => t.Dpi).Distinct().Order())
            {
                Ratios ratios = Ratios.Of(broadside, pdfjs, op, dpi);
                string best = ratios.Count == 0 ? "" : string.Create(Invariant, $"{ratios.Pairs.Min(static p => p.Ratio):0.00}x");
                text.AppendLine(Invariant, $"| {name} | {dpi?.ToString(Invariant) ?? ""} | {ratios.Count} | {ratios.MeanText} | {ratios.WorstText} | {best} |");
            }
        }

        text.AppendLine();
    }

    private static void WriteMemory(StringBuilder text, ResultSet set)
    {
        if (set.Memory.Count == 0)
        {
            return;
        }

        string[] engines = ["broadside", "pdfium", "pdfjs"];
        Dictionary<string, long> idle = set.Memory.Where(static m => m.File is null).GroupBy(static m => m.Engine).ToDictionary(static g => g.Key, static g => g.Min(static m => m.PeakRssBytes));
        text.AppendLine("### Peak memory");
        text.AppendLine();
        text.AppendLine("Peak resident memory to open each file, render every page at 150 DPI and extract its text, above the engine loaded and idle.");
        text.AppendLine();
        text.AppendLine("| File | Broadside | PDFium | pdf.js |");
        text.AppendLine("|---|---:|---:|---:|");
        text.AppendLine(Invariant, $"| *(engine loaded, nothing open: subtracted below)* | {string.Join(" | ", engines.Select(e => idle.TryGetValue(e, out long b) ? Bytes(b) : "-"))} |");
        foreach (string file in set.Memory.Where(static m => m.File is not null).Select(static m => m.File!).Distinct().Order(StringComparer.Ordinal))
        {
            var cells = engines.Select(engine =>
            {
                MemorySample? sample = set.Memory.FirstOrDefault(m => m.Engine == engine && m.File == file);
                return sample is null ? "-" : Bytes(Math.Max(0, sample.PeakRssBytes - idle.GetValueOrDefault(engine)));
            });
            text.AppendLine(Invariant, $"| `{Short(file)}` | {string.Join(" | ", cells)} |");
        }

        text.AppendLine();
    }

    private static void WritePages(StringBuilder text, ResultSet set)
    {
        IReadOnlyList<Timing> broadside = set.Engines["broadside"];
        Dictionary<string, Timing> pdfium = set.Engines["pdfium"].ToDictionary(static t => t.Key);
        Dictionary<string, Timing> pdfjs = set.Engines["pdfjs"].ToDictionary(static t => t.Key);
        text.AppendLine("<details><summary>Every page (median milliseconds)</summary>");
        text.AppendLine();
        text.AppendLine("| File | Page | Operation | DPI | Broadside | PDFium | pdf.js | Broadside allocated |");
        text.AppendLine("|---|---:|---|---:|---:|---:|---:|---:|");
        foreach (Timing timing in broadside)
        {
            string Cell(Dictionary<string, Timing> engine) => engine.TryGetValue(timing.Key, out Timing? other) ? Milliseconds(other) : "-";
            text.AppendLine(Invariant, $"| `{Short(timing.File)}` | {timing.Page + 1} | {timing.Op} | {timing.Dpi?.ToString(Invariant) ?? ""} | {Milliseconds(timing)} | {Cell(pdfium)} | {Cell(pdfjs)} | {(timing.AllocBytes is { } bytes ? Bytes(bytes) : "")} |");
        }

        text.AppendLine();
        text.AppendLine("</details>");
        text.AppendLine();
    }

    private static string Milliseconds(Timing timing) => timing.MedianMs is { } ms
        ? ms.ToString(ms < 10 ? "0.00" : ms < 100 ? "0.0" : "0", Invariant)
        : "error";

    internal static string Bytes(long bytes) => bytes switch
    {
        >= 1024 * 1024 => string.Create(Invariant, $"{bytes / (1024.0 * 1024):0.0} MB"),
        >= 1024 => string.Create(Invariant, $"{bytes / 1024.0:0} KB"),
        _ => string.Create(Invariant, $"{bytes} B"),
    };

    internal static string Short(string file) => file.Length <= 60 ? file : "..." + file[^57..];

    /// <summary>Broadside's median over another engine's, per page, for one operation and resolution.</summary>
    private sealed record Ratios(IReadOnlyList<(string Page, double Ratio)> Pairs)
    {
        public int Count => Pairs.Count;

        public double Mean => Count == 0 ? double.NaN : Math.Exp(Pairs.Average(static p => Math.Log(p.Ratio)));

        public double Worst => Count == 0 ? double.NaN : Pairs.Max(static p => p.Ratio);

        public string MeanText => Count == 0 ? "-" : string.Create(Invariant, $"{Mean:0.00}x");

        public string WorstText => Count == 0 ? "-" : string.Create(Invariant, $"{Worst:0.0}x");

        public static Ratios Of(IReadOnlyList<Timing> broadside, IReadOnlyList<Timing> other, string op, int? dpi)
        {
            Dictionary<string, Timing> theirs = other.Where(t => t.Op == op && t.Dpi == dpi && t.MedianMs > 0).ToDictionary(static t => t.Key);
            var pairs = new List<(string, double)>();
            foreach (Timing ours in broadside.Where(t => t.Op == op && t.Dpi == dpi && t.MedianMs > 0))
            {
                if (theirs.TryGetValue(ours.Key, out Timing? match))
                {
                    pairs.Add((ours.File + (ours.Page > 0 ? $" p{ours.Page + 1}" : ""), ours.MedianMs!.Value / match.MedianMs!.Value));
                }
            }

            return new Ratios(pairs);
        }
    }
}
